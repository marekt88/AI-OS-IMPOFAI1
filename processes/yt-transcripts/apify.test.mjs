import assert from "node:assert/strict";
import { test } from "node:test";
import { createApifyClient, mapApifyResult } from "./apify.mjs";

test("mapApifyResult: ok, no captions, errors, missing", () => {
  assert.deepEqual(mapApifyResult({ status: "ok", transcript: "hi", isAutoGenerated: true, language: "en", durationSeconds: 39 }), {
    status: "ok", kind: "auto", language: "en", text: "hi", duration_s: 39,
  });
  assert.equal(mapApifyResult({ status: "ok", transcript: "x", isAutoGenerated: false }).kind, "manual");
  assert.equal(mapApifyResult({ status: "ok", transcript: "  " }).status, "no-captions");
  assert.equal(mapApifyResult({ status: "unavailable", message: "This video is unavailable" }).status, "no-captions");
  assert.equal(mapApifyResult({ status: "no_captions" }).status, "no-captions");
  assert.equal(mapApifyResult({ status: "error", message: "boom" }).status, "failed");
  assert.equal(mapApifyResult(undefined).status, "failed");
});

function fakeFetch(handler) {
  const calls = [];
  const f = async (url, init) => {
    const body = JSON.parse(init.body);
    calls.push({ body, headers: init.headers });
    const result = handler(body);
    return new Response(result === null ? "" : `event: message\ndata: ${JSON.stringify({ jsonrpc: "2.0", id: body.id, result })}\n\n`, {
      status: result === null ? 202 : 200,
      headers: { "mcp-session-id": "s1" },
    });
  };
  return { f, calls };
}

test("transcripts: finds the tool by stem, batches by 25, sends the session id", async () => {
  const ids = Array.from({ length: 27 }, (_, i) => `vid${String(i).padStart(8, "0")}`);
  const { f, calls } = fakeFetch((b) => {
    if (b.method === "initialize") return { protocolVersion: "2025-06-18" };
    if (b.method === "notifications/initialized") return null;
    if (b.method === "tools/list") return { tools: [{ name: "x--youtube_comments-8e15" }, { name: "x--youtube_transcript-3b9f" }] };
    if (b.method === "tools/call") {
      assert.equal(b.params.name, "x--youtube_transcript-3b9f");
      const results = b.params.arguments.videos.map((v, i) => (i === 0 ? { videoId: v, status: "unavailable" } : { videoId: v, status: "ok", transcript: `t ${v}` }));
      return { structuredContent: { results } };
    }
    throw new Error(b.method);
  });
  const out = await createApifyClient({ token: "T", fetchImpl: f }).transcripts(ids);
  const toolCalls = calls.filter((c) => c.body.method === "tools/call");
  assert.deepEqual(toolCalls.map((c) => c.body.params.arguments.videos.length), [25, 2]);
  assert.equal(toolCalls[0].headers["mcp-session-id"], "s1");
  assert.equal(toolCalls[0].headers.authorization, "Bearer T");
  assert.equal(out.get(ids[0]).status, "no-captions");
  assert.equal(out.get(ids[1]).text, `t ${ids[1]}`);
  assert.equal(out.size, 27);
});

test("transcripts: a failed batch marks its videos failed, not the whole run", async () => {
  const { f } = fakeFetch((b) => {
    if (b.method === "tools/list") return { tools: [{ name: "youtube_transcript" }] };
    if (b.method === "tools/call") return { isError: true, content: [{ type: "text", text: "Actor run failed" }] };
    return b.method === "notifications/initialized" ? null : {};
  });
  const out = await createApifyClient({ token: "T", fetchImpl: f }).transcripts(["abc"]);
  assert.equal(out.get("abc").status, "failed");
});
