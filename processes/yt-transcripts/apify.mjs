// Apify transcript provider for yt-transcripts: calls the Apify MCP server (heyitsgautham/video-transcripts-mcp-server)
// directly over streamable HTTP (JSON-RPC), no npx / mcp-remote. APIFY_TOKEN comes from ~/.aios-runner/secrets.env.
// Price (2026-11-23): $0.003 per transcript; videos without captions, unavailable videos and errors are free.
export const APIFY_MCP_URL = "https://mcp.apify.com/?tools=heyitsgautham/video-transcripts-mcp-server";
export const BATCH = 25; // tool limit per call

// One result of the youtube_transcript tool → the provider shape used by after.mjs.
export function mapApifyResult(r) {
  if (!r) return { status: "failed", error: "apify: no result for this video" };
  if (r.status === "ok" && typeof r.transcript === "string" && r.transcript.trim()) {
    return {
      status: "ok",
      kind: r.isAutoGenerated ? "auto" : "manual",
      language: r.language ?? null,
      text: r.transcript,
      duration_s: r.durationSeconds ?? null,
    };
  }
  const why = `apify: ${r.status ?? "unknown"}${r.message ? ` (${r.message})` : ""}`.slice(0, 300);
  // errors / limits are retried as failures; everything else (no captions, unavailable, private…) as no-captions,
  // which after.mjs also retries 6/24/72 h after first seen before giving up
  if (/error|fail|limit|timeout|quota|block/i.test(String(r.status))) return { status: "failed", error: why };
  return { status: "no-captions", error: why };
}

export function createApifyClient({ token, url = APIFY_MCP_URL, fetchImpl = fetch, timeoutMs = 300_000 }) {
  let sessionId = null;
  let toolName = null;
  let nextId = 1;

  async function rpc(method, params, notify = false) {
    const headers = { "content-type": "application/json", accept: "application/json, text/event-stream", authorization: `Bearer ${token}` };
    if (sessionId) headers["mcp-session-id"] = sessionId;
    const body = notify ? { jsonrpc: "2.0", method, params } : { jsonrpc: "2.0", id: nextId++, method, params };
    const r = await fetchImpl(url, { method: "POST", headers, body: JSON.stringify(body), signal: AbortSignal.timeout(timeoutMs) });
    sessionId = r.headers.get("mcp-session-id") ?? sessionId;
    const text = await r.text();
    if (notify) return null;
    if (!r.ok) throw new Error(`apify MCP ${method}: HTTP ${r.status} ${text.slice(0, 200)}`);
    // JSON or SSE (last "data:" line)
    const raw = text.trimStart().startsWith("{") ? text : text.split("\n").filter((l) => l.startsWith("data:")).map((l) => l.slice(5)).pop();
    const msg = raw ? JSON.parse(raw) : null;
    if (!msg || msg.error) throw new Error(`apify MCP ${method}: ${JSON.stringify(msg?.error ?? text.slice(0, 200))}`);
    return msg.result;
  }

  async function connect() {
    if (toolName) return;
    await rpc("initialize", { protocolVersion: "2025-06-18", capabilities: {}, clientInfo: { name: "yt-transcripts", version: "1" } });
    await rpc("notifications/initialized", {}, true);
    const { tools = [] } = await rpc("tools/list", {});
    // the tool name carries a hash suffix (…--youtube_transcript-3b9f), so match by its stem
    toolName = tools.find((t) => /youtube_transcript(-|$)/.test(t.name))?.name;
    if (!toolName) throw new Error(`apify MCP: youtube_transcript tool not found (tools: ${tools.map((t) => t.name).join(", ")})`);
  }

  // ids → Map(videoId → provider result). Throws only when the server cannot be reached at all.
  async function transcripts(ids, { language = "en" } = {}) {
    await connect();
    const out = new Map();
    for (let i = 0; i < ids.length; i += BATCH) {
      const chunk = ids.slice(i, i + BATCH);
      try {
        const res = await rpc("tools/call", { name: toolName, arguments: { videos: chunk, language } });
        const data = res?.structuredContent ?? JSON.parse(res?.content?.find((c) => c.type === "text")?.text ?? "{}");
        if (res?.isError) throw new Error(JSON.stringify(res.content ?? "").slice(0, 300));
        const byId = new Map((data.results ?? []).map((r) => [r.videoId ?? r.input, r]));
        for (const id of chunk) out.set(id, mapApifyResult(byId.get(id)));
      } catch (err) {
        for (const id of chunk) out.set(id, { status: "failed", error: `apify: ${String(err.message).slice(0, 300)}` });
      }
    }
    return out;
  }

  return { transcripts };
}
